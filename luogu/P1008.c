#include <stdio.h>

#define H0 0b111111111
#define H1 0b000000001
#define H2 0b000000010
#define H3 0b000000100
#define H4 0b000001000
#define H5 0b000010000
#define H6 0b000100000
#define H7 0b001000000
#define H8 0b010000000
#define H9 0b100000000

short H[10] = {H0, H1, H2, H3, H4, H5, H6, H7, H8, H9};

char check(int a1, int a2, int a3) {
  char n[9] = {
      a1 / 100, a1 / 10 % 10, a1 % 10,
      a2 / 100, a2 / 10 % 10, a2 % 10,
      a3 / 100, a3 / 10 % 10, a3 % 10,
  };
  short mask = 0;
  char dirty = 0;
  for (int i = 0; i < 9; i++) {
    dirty |= !!(mask & H[n[i]]);
    mask |= H[n[i]];
  }
  return !dirty;
}

int main() {
  for (int i = 123; i < 333; i++) {
    if (check(i, i * 2, i * 3)) {
      printf("%d %d %d\n", i, i * 2, i * 3);
    }
  }
}