/*
# P1014 [NOIP 1999 普及组] Cantor 表

## 题目描述

现代数学的著名证明之一是 Georg Cantor
证明了有理数是可枚举的。他是用下面这一张表来证明这一命题的：

1/1   1/2   1/3   1/4   1/5   ...
2/1   2/2   2/3   2/4   ...
3/1   3/2   3/3   ...
4/1   4/2   ...
5/1   ...
...

我们以 Z 字形给上表的每一项编号。第一项是 $1/1$，然后是
$1/2$，$2/1$，$3/1$，$2/2$，……。

## 输入格式

输入一个整数 $N$（$1 \le N \le 10^7$）。

## 输出格式

输出表中的第 $N$ 项。

## 输入输出样例 #1

### 输入 #1

```
7

```

### 输出 #1

```
1/4
```

## 说明/提示

对于全部测试数据，$1 \le N \le 10^7$。

- 2024-11-18 0:30 数据中加入了样例，放在不计分的子任务 2 中。
*/

#include <stdio.h>

int nux(int n) { return n * (n + 1) >> 1; }

int main() {
  int N;
  scanf("%d", &N);
  int n = 0;
  while (nux(++n) < N);

  int sum = n + 1;
  int idx = N - nux(n - 1);
  if (n % 2 == 0) {
    printf("%d/%d\n", idx, sum - idx);
  } else {
    printf("%d/%d\n", sum - idx, idx);
  }
}