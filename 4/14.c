/*
题目名称：十进制数转换成其它进制数。

题目内容：编写一个程序将用户输入的十进制整数转换成指定进制的数。



输入：

先输入一个int范围内的非负整数，表示待转换的十进制数；

再输入一个[2,9]范围内的整数，表示进制。后台测评数据保证所有输入数据均符合题意。

输出：转换后的对应进制的数。转换结果的前后无任何多余字符，详见样例。



样例1:  

输入：32767 2    

输出：111111111111111

样例2:  

输入：10 3   

输出：101


样例3:  

输入：0 8   

输出：0
*/

#include <stdio.h>

int main() {
  int x, n;
  scanf("%d %d", &x, &n);
  if (x == 0) {
    putchar('0');
  }
  char str[1024];
  int i = 0;
  while (x) {
    str[i++] = x % n + '0';
    x /= n;
  }
  for (int j = i - 1; j >= 0; j--) {
    putchar(str[j]);
  }
}