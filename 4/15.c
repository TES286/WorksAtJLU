/*
题目名称：逆序存放。

题目内容：将一个由10个元素构成的int数组中的元素按逆序重新存放。



输入：10个整数

输出：按逆序重新存放后的数组元素（每个数据后面有一个空格）。



样例:  

输入：6 8 12 11 3 5 9 16 19 24  

输出：24 19 16 9 5 3 11 12 8 6
*/

#include <stdio.h>

int main() {
  int x[10];
  for (int i = 9; i >= 0; i--) {
    scanf("%d", &x[i]);
  }
  for (int i = 0; i < 10; i++) {
    printf("%d ", x[i]);
  }
}