/*
题目名称：反弹距离。

题目内容：一个球从x米高度落下，每次落地后反弹跳回原高度的一半，再落下。求第n次反弹跳多高（0<n<总弹跳次数）？它最后停在地面时（若距离小于或等于1e-5米时，即不再反弹），共经过多少米？



输入：初始高度x，反弹次数n。

输出：第n次跳起高度和经过的总米数（2个输出之间用一个空格隔开,小数点后保留6位）。



样例：

输入：100 5

输出：3.125000 299.999976



提示：

1.浮点数采用double类型；

2.如果距离小于或等于1e-5 米，则不再反弹.
*/

#include <stdio.h>

int main() {
  double x;
  int n;
  scanf("%lf %d", &x, &n);
  double hn = x;
  for (int i = 0; i < n; i++) {
    hn /= 2.0;
  }
  double total = x;
  double h = x;
  while (1) {
    h /= 2.0;
    if (h <= 1e-5) {
      break;
    }
    total += 2.0 * h;
  }
  printf("%.6f %.6f\n", hn, total);
}